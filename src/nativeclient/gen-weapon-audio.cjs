const {readFileSync, renameSync, writeFileSync} = require('node:fs');
const {resolve} = require('node:path');
const {pathToFileURL} = require('node:url');

(async () => {

const [game, output] = process.argv.slice(2);
const load = name => import(pathToFileURL(resolve(game, name)).href);
const [{chainLaunchSamples, chainPullSamples}, {rocketLaunchSamples}, {powerupSamples}] =
  await Promise.all([load('hook-audio.js'), load('rocket-audio.js'), load('powerup-audio.js')]);
const {grapfire, grappull} = JSON.parse(readFileSync(0, 'utf8'));
const pcm = input => Float32Array.from(input.pcm, sample => sample / 32768);
const damage = 'items/damage3';
const assets = [
  ['grappleLaunch', 'weapons/grapple/grapfire', grapfire.rate, chainLaunchSamples(pcm(grapfire), grapfire.rate)],
  ['grapplePull', 'weapons/grapple/grappull', grappull.rate, chainPullSamples(pcm(grappull), grappull.rate)],
  ['rocketLaunch', 'weapons/rocket/rocklf1a', 22050, rocketLaunchSamples()],
  ['quadFire', damage, 22050, powerupSamples(damage)],
  ['hastePickup', 'items/haste', 22050, powerupSamples('items/haste')],
];

const lines = ['// Generated by gen-weapon-audio.cjs.', '#pragma once', '', 'namespace nc::weapon_audio {'];
for (const [id, cue, rate, samples] of assets) {
  if (!samples?.length || !samples.every(Number.isFinite)) {
    throw new Error(`Invalid generated PCM for ${cue}`);
  }
  lines.push(`inline constexpr float ${id}[] = {`);
  for (let i = 0; i < samples.length; i += 8) {
    const row = Array.from(samples.subarray(i, i + 8), value => `${value.toExponential(8)}f`);
    lines.push(`  ${row.join(', ')},`);
  }
  lines.push('};');
}
lines.push(
  'struct Asset { const char* cue; int rate; const float* begin; const float* end; };',
  'inline constexpr Asset assets[] = {',
  ...assets.map(([id, cue, rate]) => `  {"${cue}", ${rate}, ${id}, ${id} + sizeof(${id}) / sizeof(float)},`),
  '};', '}', '',
);
writeFileSync(`${output}.tmp`, lines.join('\n'));
renameSync(`${output}.tmp`, output);
})().catch(error => { console.error(error); process.exitCode = 1; });
