'use strict';
// Writes nc_core_table.gen.cpp: for every C function the contract headers declare, a pointer filled from the loaded core library plus a forwarding function of the same name,
// so the rest of the client calls the core as if it were linked in. Linux binds them; Windows (delay-load) only checks the library has them all. The headers stay the only description of the contract.
// Usage: node src/nativeclient/gen-core-table.cjs <interface dir>        (writes next to this script; the same command with --check only compares)
const fs = require('node:fs');
const path = require('node:path');

const HEADERS = ['qrazy_core_api.h', 'render_core.h', 'text_api.h'];

function declarations(text) {
  let s = text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '').replace(/^[ \t]*#(?:[^\n]*\\\r?\n)*[^\n]*/gm, '');   // directives, with their continuation lines
  s = s.replace(/typedef\s+struct[^;{]*\{[^{}]*\}[^;]*;/g, '');   // struct typedefs
  const out = [];
  const re = /([^;{}]+?)\s*\(([^()]*)\)\s*;/g;
  let m;
  while ((m = re.exec(s))) {
    const head = m[1].replace(/\bextern\s+"C"\s*/, '').replace(/\s+/g, ' ').trim();
    const mm = /^(.*?[\s*])(\w+)$/.exec(head);
    if (!mm || /typedef/.test(head)) throw new Error('cannot read a declaration: ' + head);
    const params = m[2].replace(/\s+/g, ' ').trim();
    const list = params === 'void' || params === '' ? [] : params.split(',').map((p) => p.trim());
    const names = list.map((p, i) => { const n = /(\w+)\s*(\[\s*\d*\s*\])?$/.exec(p); if (!n || /^(void|int|double|float|char|const)$/.test(n[1]) && list.length) throw new Error(`parameter ${i + 1} of ${mm[2]} has no name: ${p}`); return n[1]; });
    out.push({ ret: mm[1].trim(), name: mm[2], params: params === '' ? 'void' : params, names });
  }
  return out;
}

function generate(dir) {
  const fns = [];
  for (const h of HEADERS) fns.push(...declarations(fs.readFileSync(path.join(dir, h), 'utf8')));
  // text_*_ptr return 32-bit wasm heap offsets; the native library leaves them out on purpose (text_api.h: use the text_*_addr twins), so they are not part of what a native client binds.
  fns.splice(0, fns.length, ...fns.filter((f) => !/^text_\w*_ptr$/.test(f.name)));
  // Additive capabilities are bound as groups by nc_coreload.
  fns.splice(0, fns.length, ...fns.filter((f) => f.name !== 'qc_ses_match' && f.name !== 'qc_ses_hud' && !f.name.startsWith('qc_ses_net_')));
  const seen = new Set();
  for (const f of fns) { if (seen.has(f.name)) throw new Error('declared twice: ' + f.name); seen.add(f.name); }
  let o = '// GENERATED by gen-core-table.cjs from the contract headers (' + HEADERS.join(', ') + '). Do not edit; run the generator again when the interface version changes.\n';
  o += '#include "nc_coretable.h"\n#if defined(_WIN32)\n#include <windows.h>\n#else\n#include "qrazy_core_api.h"\n#include "render_core.h"\n#include "text_api.h"\n#include <dlfcn.h>\n#include <vector>\n#endif\n\n';
  o += 'namespace nc {\n\n// Windows reaches the functions through delay-load, so the library only has to be checked for them (a core built before a contract addition would crash on the first call); Linux also binds them.\n';
  o += 'static const char* const kCoreFunctions[] = {\n';
  for (const f of fns) o += `  "${f.name}",\n`;
  o += '};\n\n}  // namespace nc\n\n';
  o += '#if defined(_WIN32)\nnamespace nc {\nbool bindCoreTable(void* library, std::string& missing, bool) {\n  for (const char* n : kCoreFunctions) if (!GetProcAddress((HMODULE)library, n)) { missing = n; return false; }\n  return true;\n}\n}  // namespace nc\n#else\n\n';
  o += 'extern "C" {\n';
  for (const f of fns) o += `static ${f.ret} (*p_${f.name})(${f.params});\n`;
  o += '\n';
  for (const f of fns) o += `${f.ret} ${f.name}(${f.params}) { ${f.ret.trim() === 'void' ? '' : 'return '}p_${f.name}(${f.names.join(', ')}); }\n`;
  o += '}\n\nnamespace nc {\n\n';
  o += '// Looks every contract function up in the opened library; nothing is changed unless all of them exist. On failure `missing` names the first one that does not.\n';
  o += 'bool bindCoreTable(void* library, std::string& missing, bool bind) {\n  struct Slot { const char* name; void** slot; };\n  static const Slot slots[] = {\n';
  for (const f of fns) o += `    {"${f.name}", (void**)&p_${f.name}},\n`;
  o += '  };\n  std::vector<void*> found;\n  for (const Slot& s : slots) { void* p = dlsym(library, s.name); if (!p) { missing = s.name; return false; } found.push_back(p); }\n  if (bind) for (size_t i = 0; i < found.size(); ++i) *slots[i].slot = found[i];\n  return true;\n}\n\n}  // namespace nc\n#endif\n';
  return { text: o, count: fns.length };
}

if (require.main === module) {
  const args = process.argv.slice(2), check = args.includes('--check'), dir = args.find((a) => !a.startsWith('--'));
  if (!dir) { console.error('usage: node src/nativeclient/gen-core-table.cjs <interface dir> [--check]'); process.exit(2); }
  const target = path.join(__dirname, 'nc_core_table.gen.cpp');
  try {
    const { text, count } = generate(dir);
    if (check) {
      const app = fs.readFileSync(path.join(__dirname, 'nc_app.cpp'), 'utf8');
      if (!/\brc_pickup_visual\s*\(/.test(app) || !/\brc_view_weapon_visual\s*\(/.test(app) ||
          /\b(?:kModels|kGuns)\b|"ammo_"|"(?:assets\/models\/)?[^"\n]+\.v\d+\.glb"/.test(app)) {
        throw new Error('Native pickup and view-weapon visuals must come from the core and resolve files through the model manifest');
      }
      const same = fs.existsSync(target) && fs.readFileSync(target, 'utf8') === text;
      console.log(same ? `up to date (${count} functions)` : 'OUT OF DATE: run the generator');
      process.exit(same ? 0 : 1);
    }
    fs.writeFileSync(target, text); console.log(`${count} functions -> ${target}`);
  } catch (e) { console.error(e.message); process.exit(1); }
}
module.exports = { generate };
